-- Canonical skill catalog used to normalize skills extracted from CVs (and later, job skills).
-- Aliases are stored lower-cased with single spaces; normalization happens in SkillNormalizer.

CREATE TABLE skills (
    id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    slug        VARCHAR(80)  NOT NULL,
    name        VARCHAR(80)  NOT NULL,
    category    VARCHAR(30)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_skills_slug UNIQUE (slug),
    CONSTRAINT uq_skills_name UNIQUE (name),
    CONSTRAINT ck_skills_category CHECK (category IN ('PROGRAMMING_LANGUAGE', 'FRAMEWORK_LIBRARY',
        'DATABASE', 'CLOUD_DEVOPS', 'TOOL', 'METHODOLOGY', 'SOFT_SKILL', 'OTHER'))
);

CREATE TABLE skill_aliases (
    alias     VARCHAR(120) PRIMARY KEY,
    skill_id  UUID         NOT NULL REFERENCES skills (id) ON DELETE CASCADE,
    CONSTRAINT ck_skill_aliases_normalized CHECK (alias = lower(btrim(alias)) AND alias <> '')
);

CREATE INDEX ix_skill_aliases_skill ON skill_aliases (skill_id);

